/**
 * Generate `src/mcp-manifest.ts`: each office app's MCP `instructions` and `tools/list`, taken from its real server, so
 * the combined server (`aiplus-office mcp`) can answer `initialize` and `tools/list` without starting any app.
 *
 *   node --import tsx scripts/mcp-manifest.mjs
 *
 * Each app is provisioned through the bundle (`dist/aiplus-office.mjs <app> path`, the latest release) and its server is
 * started raw, with the flags the per-app proxy gives it, confined to a temporary folder. The GridCraft list is stored
 * unfiltered (the gateway filters it at run time). The temporary folder's path must not appear in the output: it would
 * leak a local path into a public repository. Re-run after an app release changes its tools, then `npm run build`.
 *
 * See change: office-mcp-one-server.
 */
import { execFileSync, spawn } from "node:child_process";
import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import * as readline from "node:readline";
import { fileURLToPath } from "node:url";
import { CRAFT_APPS } from "../src/registry.ts";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const bundle = path.join(root, "dist", "aiplus-office.mjs");
const outFile = path.join(root, "src", "mcp-manifest.ts");
const jail = fs.mkdtempSync(path.join(os.tmpdir(), "aiplus-office-manifest-"));

function serverArgs(app) {
  const c = app.mcp.confinement;
  const args = c === "root" ? ["mcp", "--root", jail] : c === "automation-roots" ? ["mcp", "--automation-read-root", jail, "--automation-write-root", jail] : ["mcp"];
  if (app.mcp.compactFlag) args.push(app.mcp.compactFlag);
  return args;
}

function capture(bin, args) {
  return new Promise((resolve, reject) => {
    const c = spawn(bin, args, { stdio: ["pipe", "pipe", "ignore"] });
    const timer = setTimeout(() => (c.kill(), reject(new Error(`${bin}: no answer in 60 s`))), 60_000);
    const send = (o) => c.stdin.write(`${JSON.stringify({ jsonrpc: "2.0", ...o })}\n`);
    let init;
    readline.createInterface({ input: c.stdout }).on("line", (line) => {
      let m;
      try {
        m = JSON.parse(line);
      } catch {
        return;
      }
      if (m.id === 1) {
        init = m.result;
        send({ method: "notifications/initialized" });
        send({ id: 2, method: "tools/list" });
      } else if (m.id === 2) {
        clearTimeout(timer);
        c.stdin.end();
        resolve({ init, tools: m.result.tools });
      }
    });
    c.on("error", reject);
    send({ id: 1, method: "initialize", params: { protocolVersion: "2025-06-18", capabilities: {}, clientInfo: { name: "aiplus-office-manifest", version: "0" } } });
  });
}

const apps = {};
for (const app of CRAFT_APPS) {
  const bin = execFileSync(process.execPath, [bundle, app.id, "path"], { encoding: "utf8" }).trim();
  const { init, tools } = await capture(bin, serverArgs(app));
  apps[app.id] = { version: init?.serverInfo?.version ?? "unknown", instructions: typeof init?.instructions === "string" ? init.instructions : "", tools };
  process.stderr.write(`${app.id} ${apps[app.id].version}: ${tools.length} tools\n`);
}
fs.rmSync(jail, { recursive: true, force: true });

const json = JSON.stringify(apps, null, 1);
for (const leak of [jail, os.homedir()]) {
  if (json.includes(leak)) throw new Error(`the manifest would carry a local path (${leak}); not written`);
}
fs.writeFileSync(
  outFile,
  `/**
 * GENERATED by scripts/mcp-manifest.mjs — do not edit. Each app's MCP instructions and tools/list from its real server
 * (Linux build; GridCraft unfiltered), for the combined server's answers before an app runs. See change:
 * office-mcp-one-server.
 */
import type { McpManifest } from "./mcp-hub.js";

export const MCP_MANIFEST: McpManifest = ${json};
`,
);
process.stderr.write(`wrote ${path.relative(root, outFile)}\n`);
